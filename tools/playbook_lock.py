#!/usr/bin/env python3
"""Guard the stability of the playbook's question set.

The playbook claims that answers accumulate into a comparison across
assessments. That claim holds only while a question id keeps meaning the same
thing. Rewording `K1` between the third and fourth assessment does not announce
itself: the answers still line up in a column, they are simply no longer answers
to the same question, and every comparison drawn from them is quietly wrong.

Prose cannot enforce that. This can. `playbook/questions.lock` records a hash of
each question's text; CI fails when an existing id's text changes or disappears.
Appending new questions is always allowed.

    python3 tools/playbook_lock.py --check     # CI
    python3 tools/playbook_lock.py --update    # after appending questions

Changing an existing question is not forbidden — sometimes a question really was
wrong. It is made deliberate: you must run --update, and the diff shows up in
review, where somebody can ask what happens to the assessments that answered the
old wording.
"""

from __future__ import annotations

import argparse
import hashlib
import sys
from pathlib import Path

try:
    import yaml
except ImportError:  # pragma: no cover - dependency guidance only
    sys.exit("PyYAML is required:  pip install pyyaml")

ROOT = Path(__file__).resolve().parent.parent
QUESTIONS = ROOT / "playbook" / "questions.yaml"
LOCK = ROOT / "playbook" / "questions.lock"

HEADER = (
    "# Generated by tools/playbook_lock.py. Do not edit by hand.\n"
    "# A hash per question id. CI fails when an existing question's text changes\n"
    "# or an id disappears, because either silently invalidates every comparison\n"
    "# drawn across assessments that used it. Appending new questions is free.\n"
)


def fingerprint(text: str) -> str:
    normalised = " ".join(text.split())
    return hashlib.sha256(normalised.encode("utf-8")).hexdigest()[:16]


def read_questions() -> dict[str, str]:
    document = yaml.safe_load(QUESTIONS.read_text(encoding="utf-8"))
    found: dict[str, str] = {}
    for section in document.get("sections", []):
        prefix = section["id"]
        for question in section.get("questions", []):
            identifier = question["id"]
            if not identifier.startswith(prefix):
                sys.exit(f"question {identifier} is not prefixed by its section {prefix}")
            if identifier in found:
                sys.exit(f"duplicate question id: {identifier}")
            found[identifier] = fingerprint(question["text"])
    return found


def read_lock() -> dict[str, str]:
    if not LOCK.is_file():
        return {}
    locked: dict[str, str] = {}
    for line in LOCK.read_text(encoding="utf-8").splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#"):
            continue
        identifier, _, digest = stripped.partition(":")
        locked[identifier.strip()] = digest.strip()
    return locked


def write_lock(questions: dict[str, str]) -> None:
    body = "".join(f"{identifier}: {digest}\n" for identifier, digest in sorted(questions.items()))
    LOCK.write_text(HEADER + body, encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--check", action="store_true", help="fail if an existing question changed")
    group.add_argument("--update", action="store_true", help="rewrite the lock file")
    arguments = parser.parse_args()

    questions = read_questions()

    if arguments.update:
        write_lock(questions)
        print(f"Locked {len(questions)} question(s) in {LOCK.relative_to(ROOT)}")
        return 0

    locked = read_lock()
    if not locked:
        sys.exit(f"{LOCK.relative_to(ROOT)} is missing. Run --update to create it.")

    changed = [i for i, digest in locked.items() if i in questions and questions[i] != digest]
    removed = [i for i in locked if i not in questions]
    added = [i for i in questions if i not in locked]

    for identifier in added:
        print(f"  new    {identifier}")

    if not changed and not removed:
        print(f"Question set stable: {len(locked)} locked, {len(added)} appended.")
        if added:
            print("Run --update to record the additions.")
            return 1
        return 0

    print("Question set is not stable.\n")
    for identifier in changed:
        print(f"  CHANGED  {identifier}  its wording no longer matches the lock")
    for identifier in removed:
        print(f"  REMOVED  {identifier}  answers to it exist and now refer to nothing")
    print(
        "\nEvery assessment that answered these answered a different question than the one\n"
        "now recorded under that id. If the change is intended, run --update in the same\n"
        "commit and say in the message what happens to the assessments already answered."
    )
    return 1


if __name__ == "__main__":
    sys.exit(main())
